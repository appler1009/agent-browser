import puppeteer from 'puppeteer-core';
const [,, wsUrl, fixtures] = process.argv;
const log = (...a) => console.log(...a);
const browser = await puppeteer.connect({ browserWSEndpoint: wsUrl, defaultViewport: null });
log('version:', await browser.version());
const pages = await browser.pages();
log('pages:', pages.length);
const page = pages[0] ?? await browser.newPage();
await page.goto(`file://${fixtures}/login.html`, { waitUntil: 'load' });
log('title:', await page.title());
log('eval:', await page.evaluate(() => 1 + 2), await page.evaluate(() => document.querySelector('h1').textContent));
await page.type('#u', 'alice');
await page.type('#p', 's3cret');
log('values:', await page.$eval('#u', e => e.value), await page.$eval('#p', e => e.value));
await Promise.all([page.waitForNavigation({ waitUntil: 'load' }), page.click('button[type=submit]')]);
log('after submit url:', page.url().split('/').pop());
await page.waitForFunction(() => document.getElementById('who').textContent.includes('alice'));
log('who:', await page.$eval('#who', e => e.textContent));
const shot = await page.screenshot({ type: 'png' });
log('screenshot bytes>1000:', shot.length > 1000);
await page.goto(`file://${fixtures}/modal.html`);
const covered = await page.$('#buy');
await (await page.$('#accept')).click();
await page.click('#buy');
log('buy msg:', await page.$eval('#msg', e => e.textContent));
log('console/dialog:');
const dialogs = [];
page.on('dialog', d => { dialogs.push(d.message()); d.accept(); });
await page.goto(`file://${fixtures}/search.html`);
await page.click('#al');
await new Promise(r => setTimeout(r, 300));
log('dialogs seen:', JSON.stringify(dialogs));
const np = await browser.newPage();
await np.goto(`file://${fixtures}/done.html?user=zed`);
log('new page text:', await np.$eval('#who', e => e.textContent));
log('pages now:', (await browser.pages()).length);
await np.close();
const cdp = await page.createCDPSession();
const ax = await cdp.send('Accessibility.getFullAXTree');
log('ax nodes>2:', ax.nodes.length > 2);
try { await cdp.send('Fetch.enable'); log('Fetch.enable: UNEXPECTED success'); } catch (e) { log('Fetch.enable fails loudly:', e.message); }
await browser.disconnect();
log('DONE');
