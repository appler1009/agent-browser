import { chromium } from 'playwright-core';
const [,, wsUrl, fixtures] = process.argv;
const log = (...a) => console.log(...a);
const browser = await chromium.connectOverCDP(wsUrl, { timeout: 20000 });
log('connected; contexts:', browser.contexts().length);
const context = browser.contexts()[0];
const page = context.pages()[0] ?? await context.newPage();
await page.goto(`file://${fixtures}/login.html`);
log('title:', await page.title());
await page.fill('#u', 'alice');
await page.fill('#p', 's3cret');
log('value:', await page.inputValue('#u'));
await Promise.all([page.waitForURL(/done\.html/), page.click('button[type=submit]')]);
log('url:', page.url().split('/').pop());
log('text:', await page.textContent('#who'));
log('getByRole heading:', await page.getByRole('heading').first().textContent());
const png = await page.screenshot();
log('screenshot ok:', png.length > 1000);
await browser.close().catch(() => {});
log('DONE');
